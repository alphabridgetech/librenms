                $resolved_ip = gethostbyname($targetIp);
                if ($resolved_ip === $targetIp) {
                    $failedHosts[] = "$ipHost (unresolved)";
                    continue;
                }
                $targetIp = $resolved_ip;
            }

            $cmd = sprintf(
                '/usr/bin/snmptrap -v 2c -c %s udp:%s:%d 0 %s %s s %s %s s %s %s s %s %s s %s %s s %s %s s %s %s s %s 2>&1',
                escapeshellarg('public'),
                escapeshellarg($targetIp),
                $port,
                escapeshellarg('SNMPv2-SMI::enterprises.58158.9.188.6.1.0.6'),
                escapeshellarg('SNMPv2-SMI::enterprises.58158.9.188.1'), escapeshellarg('127.0.0.1'),
                escapeshellarg('SNMPv2-SMI::enterprises.58158.9.188.2'), escapeshellarg('LibreNMS-Server'),
                escapeshellarg('SNMPv2-SMI::enterprises.58158.9.188.3'), escapeshellarg('ACTIVE'),
                escapeshellarg('SNMPv2-SMI::enterprises.58158.9.188.4'), escapeshellarg('Equipment'),
                escapeshellarg('SNMPv2-SMI::enterprises.58158.9.188.5'), escapeshellarg('Info'),
                escapeshellarg('SNMPv2-SMI::enterprises.58158.9.188.6'), escapeshellarg(date('Y M j H:i:s ')),
                escapeshellarg('SNMPv2-SMI::enterprises.58158.9.188.7'), escapeshellarg('Test SNMP Trap Connection')
            );
            $output = [];
            $retval = 0;
            exec($cmd, $output, $retval);

            if ($retval === 0) {
                $sentCount++;
            } else {
                if (($socket = socket_create(AF_INET, SOCK_DGRAM, SOL_UDP)) !== false) {
                    $test_trap = "localhost\nUDP: [127.0.0.1]:54321->[127.0.0.1]:162\nDISMAN-EVENT-MIB::sysUpTimeInstance 1:0:00:00.00\nSNMPv2-MIB::snmpTrapOID.0 SNMPv2-SMI::enterprises.9.9.41.2.0.1\n";
                    if (socket_sendto($socket, $test_trap, strlen($test_trap), 0, $targetIp, $port) !== false) {
                        $sentCount++;
                    } else {
                        $failedHosts[] = "$ipHost (send failed)";
                    }
                    socket_close($socket);
                } else {
                    $failedHosts[] = "$ipHost (send failed)";
                }
            }
        }

        if ($sentCount > 0 && empty($failedHosts)) {
            return response()->json([
                'success' => true,
                'message' => "Test SNMP trap packet sent successfully to {$sentCount} target server(s).",
            ]);
        } elseif ($sentCount > 0) {
            return response()->json([
                'success' => true,
                'message' => "Sent test SNMP trap to {$sentCount} host(s), but failed for: " . implode(', ', $failedHosts),
