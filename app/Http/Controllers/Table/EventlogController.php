    public function testForwardSnmpTrap(\Illuminate\Http\Request $request)
    {
        $request->validate([
            'snmptrap_ip' => 'required|string',
            'snmptrap_port' => 'required|integer|between:1,65535',
        ]);

        $rawInput = $request->input('snmptrap_ip');
        $port = (int) $request->input('snmptrap_port');

        $ipList = array_filter(array_map('trim', preg_split('/[\s,]+/', $rawInput)));
        if (empty($ipList)) {
            return response()->json(['success' => false, 'message' => 'Please enter at least one valid IP address or hostname.'], 422);
        }

        $sentCount = 0;
        $failedHosts = [];

        foreach ($ipList as $ipHost) {
            $targetIp = $ipHost;
            if (! filter_var($targetIp, FILTER_VALIDATE_IP)) {
                if (! preg_match('/^([a-z0-9]+(-[a-z0-9]+)*\.)+[a-z]{2,}$/i', $targetIp) && ! preg_match('/^[a-z0-9]+(-[a-z0-9]+)*$/i', $targetIp)) {
                    $failedHosts[] = "$ipHost (invalid format)";
